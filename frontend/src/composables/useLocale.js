async function detectLanguage() {
  const saved = localStorage.getItem(STORAGE_KEY)
  if (saved) { lang.value = saved; return }
  try {
    const res = await fetch('https://api.synapicsearch.com/detect-lang')
    const data = await res.json()
    lang.value = data.lang || 'en'
    localStorage.setItem(STORAGE_KEY, lang.value)
  } catch { lang.value = 'en' }
}

function setLanguage(newLang) {
  lang.value = newLang
  localStorage.setItem(STORAGE_KEY, newLang)
}

function t(section, key) {
  const l = lang.value === 'tr' ? tr : en
  return l[section]?.[key] ?? key
}

export { lang, detectLanguage, setLanguage, tr, en, t }